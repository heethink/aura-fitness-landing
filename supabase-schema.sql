-- 1. consultations (상담 신청 내역) 테이블 생성
CREATE TABLE IF NOT EXISTS public.consultations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    visit_date TEXT NOT NULL,
    visit_time TEXT NOT NULL,
    interests TEXT[] DEFAULT '{}',
    status TEXT DEFAULT '대기중',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 테이블 코멘트 추가
COMMENT ON TABLE public.consultations IS 'AURA 피트니스 클럽 1회 무료 체험 및 상담 신청자 명단';

-- 3. 실시간(Realtime) 구독 활성화
ALTER PUBLICATION supabase_realtime ADD TABLE public.consultations;

-- 4. RLS(행 단위 보안) 활성화 및 정책 설정
ALTER TABLE public.consultations ENABLE ROW LEVEL SECURITY;

-- 4-1. 누구나 상담 신청서를 접수할 수 있도록 허용 (INSERT)
CREATE POLICY "누구나 상담 신청 가능" 
ON public.consultations 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- 4-2. 관리자 페이지에서 신청자 목록을 조회할 수 있도록 허용 (SELECT)
CREATE POLICY "상담 신청 내역 조회 가능" 
ON public.consultations 
FOR SELECT 
TO anon, authenticated 
USING (true);

-- 4-3. 관리자 페이지에서 상태 변경이 가능하도록 허용 (UPDATE)
CREATE POLICY "상담 상태 변경 가능" 
ON public.consultations 
FOR UPDATE 
TO anon, authenticated 
USING (true);

-- 4-4. 관리자 페이지에서 신청서 삭제가 가능하도록 허용 (DELETE)
CREATE POLICY "상담 신청서 삭제 가능" 
ON public.consultations 
FOR DELETE 
TO anon, authenticated 
USING (true);
